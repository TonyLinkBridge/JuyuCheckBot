-- JUYU Domain Check backend schema
-- Run once in Supabase SQL Editor, then set SUPABASE_URL and
-- SUPABASE_SERVICE_ROLE_KEY only in the Bot's server environment.

create table if not exists public.domain_reports (
  report_token text primary key,
  telegram_user_id bigint not null,
  source text not null default 'direct',
  domain text not null,
  intent text check (intent is null or intent in ('owner', 'buyer', 'research')),
  -- The following legacy score columns remain only for backward compatibility.
  -- JUYU-EVIDENCE-2.1 does not expose or calculate a proprietary domain score.
  score smallint check (score between 0 and 100),
  grade text check (grade in ('S', 'A', 'B', 'C', 'D')),
  score_version text,
  confidence text check (confidence in ('low', 'medium')),
  data_coverage smallint check (data_coverage between 0 and 100),
  dimension_scores jsonb,
  report jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.growth_events (
  id bigint generated by default as identity primary key,
  event_name text not null,
  telegram_user_id bigint not null,
  source text not null default 'direct',
  domain text,
  report_token text,
  intent text check (intent is null or intent in ('owner', 'buyer', 'research')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.user_profiles (
  telegram_user_id bigint primary key,
  telegram_username text,
  telegram_first_name text,
  telegram_last_name text,
  first_source text not null default 'direct',
  last_source text not null default 'direct',
  last_source_label text not null default '直接打开 Telegram Bot',
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create table if not exists public.bot_sessions (
  telegram_user_id bigint primary key references public.user_profiles(telegram_user_id) on delete cascade,
  flow text not null check (flow in ('buy', 'sell', 'register', 'contact')),
  step text not null,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.leads (
  id bigint generated always as identity primary key,
  lead_type text not null check (lead_type in ('buy', 'sell', 'contact')),
  telegram_user_id bigint not null references public.user_profiles(telegram_user_id) on delete cascade,
  username text not null default '',
  data jsonb not null default '{}'::jsonb,
  status text not null default 'new',
  created_at timestamptz not null default now()
);

create index if not exists domain_reports_user_created_idx
  on public.domain_reports (telegram_user_id, created_at desc);
create index if not exists domain_reports_domain_created_idx
  on public.domain_reports (domain, created_at desc);
create index if not exists growth_events_name_created_idx
  on public.growth_events (event_name, created_at desc);
create index if not exists growth_events_source_created_idx
  on public.growth_events (source, created_at desc);
create index if not exists growth_events_user_created_idx
  on public.growth_events (telegram_user_id, created_at desc);
create index if not exists leads_created_at_idx
  on public.leads (created_at desc);
create index if not exists leads_type_status_idx
  on public.leads (lead_type, status, created_at desc);

