alter table public.user_profiles add column if not exists telegram_username text;
alter table public.user_profiles add column if not exists telegram_first_name text;
alter table public.user_profiles add column if not exists telegram_last_name text;

update public.user_profiles
set last_source_label = case
  when last_source = 'direct' then '直接打开 Telegram Bot'
  when last_source = 'channel' then 'JUYU Telegram 频道'
  when last_source = 'juyucom' then 'JUYU 官网'
  when last_source = 'share' then '报告分享入口'
  when last_source = 'referral' then '朋友分享链接'
  when last_source = 'juyu_check_bot' then 'JUYU 域名体检 Bot'
  when last_source = 'juyu_domain_bot' then 'JUYU 聚域助手'
  when last_source like 'morningbrief\_%' escape '\' then 'Telegram 频道活动：' || last_source
  else '活动来源：' || last_source
end
where last_source_label is null or last_source_label = '';

alter table public.user_profiles alter column last_source_label set default '直接打开 Telegram Bot';
alter table public.user_profiles alter column last_source_label set not null;

update public.domain_reports
set score = null,
    grade = null,
    score_version = null,
    confidence = null,
    data_coverage = null,
    dimension_scores = null
where coalesce(report->>'reportVersion', '') like 'JUYU-EVIDENCE-%';

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists domain_reports_set_updated_at on public.domain_reports;
create trigger domain_reports_set_updated_at
before update on public.domain_reports
for each row execute function public.set_updated_at();

create or replace function public.clear_legacy_domain_scores()
returns trigger
language plpgsql
as $$
begin
  if coalesce(new.report->>'reportVersion', '') like 'JUYU-EVIDENCE-%' then
    new.score = null;
    new.grade = null;
    new.score_version = null;
    new.confidence = null;
    new.data_coverage = null;
    new.dimension_scores = null;
  end if;
  return new;
end;
$$;

drop trigger if exists domain_reports_clear_legacy_scores on public.domain_reports;
create trigger domain_reports_clear_legacy_scores
before insert or update on public.domain_reports
for each row execute function public.clear_legacy_domain_scores();

